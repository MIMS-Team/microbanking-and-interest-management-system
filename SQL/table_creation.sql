--create branch table

CREATE TABLE Branch (
    Branch_ID SMALLSERIAL PRIMARY KEY,
    Name VARCHAR(100) NOT NULL UNIQUE,
    Address VARCHAR(255),
    Phone_No VARCHAR(20),
    Is_Active BOOLEAN NOT NULL DEFAULT TRUE, 
    Email VARCHAR(100) UNIQUE,
    Opened_date DATE NOT NULL DEFAULT CURRENT_DATE
);

--create roles  table

CREATE TABLE Role (
    Role_ID CHAR(1) PRIMARY KEY,
    Title VARCHAR(50) NOT NULL UNIQUE
);

--create employee table

CREATE TABLE Employee (
    Employee_ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    Branch_ID SMALLINT NOT NULL, 
    Name VARCHAR(100) NOT NULL,
    UserName VARCHAR(50) UNIQUE NOT NULL,
    Password VARCHAR(255) NOT NULL, 
    Email VARCHAR(100) UNIQUE NOT NULL,
    Mobile_No VARCHAR(20),
    Role_ID CHAR(1) NOT NULL, 
    Is_Active BOOLEAN NOT NULL DEFAULT TRUE, 
    Opened_date DATE NOT NULL DEFAULT CURRENT_DATE,
    
    CONSTRAINT fk_employee_branch FOREIGN KEY (Branch_ID) REFERENCES Branch(Branch_ID) ON DELETE RESTRICT,
    CONSTRAINT fk_employee_role FOREIGN KEY (Role_ID) REFERENCES Role(Role_ID) ON DELETE RESTRICT ON UPDATE CASCADE
);

--crete otp for employee table
CREATE TABLE otpe (             -- OTPs for employees
    otp_id INT GENERATED BY DEFAULT AS IDENTITY (CYCLE),
    employee_id INT NOT NULL,
    otp_hash VARCHAR(255) NOT NULL,
    purpose VARCHAR(100),
    is_success BOOLEAN,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP DEFAULT (CURRENT_TIMESTAMP + INTERVAL '600 seconds'),
    PRIMARY KEY (otp_id),
    FOREIGN KEY (employee_id) REFERENCES employee(employee_id) ON DELETE CASCADE
);


--sender id to send ech type of otp's
CREATE TABLE  otpsenders (
    id SERIAL PRIMARY KEY,
    employee_id INT NOT NULL UNIQUE,
    otprole VARCHAR(10) NOT NULL,
    CONSTRAINT fk_employee 
        FOREIGN KEY (employee_id) 
        REFERENCES employee(employee_id) 
        ON DELETE CASCADE
);
