CREATE TABLE branches (
  id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  code VARCHAR(12) NOT NULL,
  name VARCHAR(100) NOT NULL,
  address TEXT DEFAULT NULL,
  phone VARCHAR(12) DEFAULT NULL,
  email VARCHAR(254) DEFAULT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (id),
  CONSTRAINT branches_code UNIQUE (code)
);


CREATE TABLE staff (
  id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  password_hash TEXT NOT NULL,
  role VARCHAR(32) NOT NULL CHECK (role IN ('admin', 'higher_manager', 'manager', 'agent')),
  branch_id INTEGER DEFAULT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (id),
  CONSTRAINT staff_email UNIQUE (email),
  CONSTRAINT staff_ibfk_branch FOREIGN KEY (branch_id) REFERENCES branches (id) ON DELETE RESTRICT
);
CREATE INDEX staff_branch_id ON staff (branch_id);

CREATE TABLE staff_authentication (
  employee_id INTEGER NOT NULL,
  password_hash TEXT NOT NULL,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TIMESTAMP(3) WITHOUT TIME ZONE NULL DEFAULT NULL,
  last_login_at TIMESTAMP(3) WITHOUT TIME ZONE NULL DEFAULT NULL,
  updated_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC') ,
  PRIMARY KEY (employee_id),
  CONSTRAINT fk_staff_auth_employee FOREIGN KEY (employee_id) REFERENCES staff (id) ON DELETE CASCADE
);


CREATE TABLE employee_sessions (
  token_hash VARCHAR(64) NOT NULL,
  employee_id INTEGER NOT NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  last_activity_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  expires_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
  revoked_at TIMESTAMP(3) WITHOUT TIME ZONE NULL DEFAULT NULL,
  ip_address VARCHAR(45) DEFAULT NULL,
  user_agent TEXT DEFAULT NULL,
  PRIMARY KEY (token_hash),
  CONSTRAINT fk_sessions_employee FOREIGN KEY (employee_id) REFERENCES staff (id) ON DELETE CASCADE
);
CREATE INDEX employee_sessions_idx_sessions_employee ON employee_sessions (employee_id);
CREATE INDEX employee_sessions_idx_sessions_expires_at ON employee_sessions (expires_at);

CREATE TABLE otp_challenges (
  id VARCHAR(64) NOT NULL,
  employee_id INTEGER NOT NULL,
  purpose VARCHAR(32) NOT NULL CHECK (purpose IN ('login', 'password_reset', 'employee_creation', 'employee_deactivation')),
  code_hash VARCHAR(128) NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 5,
  expires_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
  consumed_at TIMESTAMP(3) WITHOUT TIME ZONE NULL DEFAULT NULL,
  metadata JSONB DEFAULT NULL,
  is_pending SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (id),
  CONSTRAINT fk_otp_employee FOREIGN KEY (employee_id) REFERENCES staff (id) ON DELETE CASCADE
);
CREATE INDEX otp_challenges_idx_otp_employee_purpose ON otp_challenges (employee_id, purpose, created_at);

CREATE TABLE otp_resend_reservations (
  challenge_id VARCHAR(64) NOT NULL,
  reservation_token VARCHAR(64) NOT NULL,
  replacement_id VARCHAR(64) NOT NULL,
  lease_expires_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (challenge_id),
  CONSTRAINT fk_resend_challenge FOREIGN KEY (challenge_id) REFERENCES otp_challenges (id) ON DELETE CASCADE
);


CREATE TABLE authentication_audit (
  id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  employee_id INTEGER DEFAULT NULL,
  email VARCHAR(254) NOT NULL,
  event_type VARCHAR(50) NOT NULL,
  ip_address VARCHAR(45) DEFAULT NULL,
  user_agent TEXT DEFAULT NULL,
  details JSONB DEFAULT NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY (id),
  CONSTRAINT fk_audit_employee FOREIGN KEY (employee_id) REFERENCES staff (id) ON DELETE SET NULL
);
CREATE INDEX authentication_audit_idx_audit_email ON authentication_audit (email, created_at);
CREATE INDEX authentication_audit_idx_audit_employee ON authentication_audit (employee_id, created_at);
CREATE INDEX authentication_audit_idx_audit_event ON authentication_audit (event_type, created_at);

CREATE UNIQUE INDEX staff_email_folded ON staff(lower(email));
CREATE UNIQUE INDEX branches_code_folded ON branches(lower(code));
