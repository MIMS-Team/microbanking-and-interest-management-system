ALTER TABLE job_runs ADD COLUMN owner_token CHAR(64) NULL,
 ADD COLUMN attempt INTEGER NOT NULL DEFAULT 1,
 ADD COLUMN notification_status VARCHAR(20) NULL;


CREATE TABLE job_claims (
  job VARCHAR(60) NOT NULL,
  boundary VARCHAR(40) NOT NULL,
  PRIMARY KEY(job,boundary),
  status VARCHAR(32) NOT NULL CHECK (status IN ('running','complete','failed')),
  owner_token CHAR(64) NOT NULL,
  lease_until TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
  retry_after TIMESTAMP(3) WITHOUT TIME ZONE NULL,
  attempt INTEGER NOT NULL,
  run_id BIGINT NOT NULL,
  FOREIGN KEY(run_id) REFERENCES job_runs(id)
);
CREATE INDEX job_claims_stale_jobs ON job_claims (status,lease_until);

INSERT INTO job_claims(job,boundary,status,owner_token,lease_until,attempt,run_id)
 SELECT j.job,j.boundary,'complete',REPEAT('0',64),j.finished_at,1,j.id FROM job_runs j
 JOIN (SELECT job,boundary,MAX(id) AS id FROM job_runs WHERE status='complete' GROUP BY job,boundary) last ON last.id=j.id;

CREATE TABLE backup_inventory (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_run_id BIGINT NOT NULL UNIQUE,
  file_path VARCHAR(1000) NOT NULL,
  checksum CHAR(64) NOT NULL,
  key_id VARCHAR(60) NOT NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  deleted_at TIMESTAMP(3) WITHOUT TIME ZONE NULL,
  exported_at TIMESTAMP(3) WITHOUT TIME ZONE NULL,
  FOREIGN KEY(job_run_id) REFERENCES job_runs(id)
);

