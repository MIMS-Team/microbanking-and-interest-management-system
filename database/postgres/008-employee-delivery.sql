CREATE TABLE employee_invitations (
  token_hash CHAR(64)  PRIMARY KEY,
  employee_id INTEGER NOT NULL,
  purpose VARCHAR(32) NOT NULL CHECK (purpose IN ('onboarding')),
  binding_hash CHAR(64)  NOT NULL,
  expires_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL,
  consumed_at TIMESTAMP(3) WITHOUT TIME ZONE NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  FOREIGN KEY(employee_id) REFERENCES staff(id)
);
CREATE INDEX employee_invitations_invitation_employee ON employee_invitations (employee_id,consumed_at,expires_at);

CREATE TABLE employee_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL,
  kind VARCHAR(32) NOT NULL CHECK (kind IN ('onboarding','account_update','password_change','account_status')),
  status VARCHAR(32) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sending','sent','failed','exhausted')),
  attempts SMALLINT NOT NULL DEFAULT 0,
  owner CHAR(64)  NULL,
  available_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  lease_until TIMESTAMP(3) WITHOUT TIME ZONE NULL,
  delivered_at TIMESTAMP(3) WITHOUT TIME ZONE NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  error_code VARCHAR(40) NULL,
  FOREIGN KEY(employee_id) REFERENCES staff(id)
);
CREATE INDEX employee_notifications_notification_pending ON employee_notifications (status,available_at,lease_until);
CREATE INDEX employee_notifications_notification_employee ON employee_notifications (employee_id,kind,created_at);

CREATE TABLE action_receipts (
  actor_id INTEGER NOT NULL,
  operation_key VARCHAR(100)  NOT NULL,
  fingerprint CHAR(64)  NOT NULL,
  result JSONB NULL,
  created_at TIMESTAMP(3) WITHOUT TIME ZONE NOT NULL DEFAULT (clock_timestamp() AT TIME ZONE 'UTC'),
  PRIMARY KEY(actor_id,operation_key),
  FOREIGN KEY(actor_id) REFERENCES staff(id)
);

